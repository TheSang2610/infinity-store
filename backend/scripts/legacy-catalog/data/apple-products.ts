import type { Product, ProductColor, ProductVariant } from "./products";

type PricedStorage = { storage: string; price: string; ram?: string };
type ColorAsset = ProductColor & { image: string };

function macVariants(slug: string, configurations: PricedStorage[], colors: ColorAsset[]): ProductVariant[] {
  return configurations.flatMap((configuration) => colors.map((color) => ({
    id: `${slug}-${configuration.ram}-${configuration.storage}-${color.name}`.toLowerCase().replace(/[^a-z0-9]+/g, "-"),
    name: [configuration.ram, configuration.storage, color.name].filter(Boolean).join(" / "),
    ram: configuration.ram,
    storage: configuration.storage,
    color: color.name,
    colorHex: color.hex,
    price: configuration.price,
    stock: 10,
    image: color.image,
  })));
}

function ipadVariants(slug: string, configurations: PricedStorage[], colors: ColorAsset[]): ProductVariant[] {
  return configurations.flatMap((configuration) => colors.map((color) => ({
    id: `${slug}-${configuration.storage}-${color.name}`.toLowerCase().replace(/[^a-z0-9]+/g, "-"),
    name: `${configuration.storage} / ${color.name}`,
    storage: configuration.storage,
    color: color.name,
    colorHex: color.hex,
    price: configuration.price,
    stock: 10,
    image: color.image,
  })));
}

